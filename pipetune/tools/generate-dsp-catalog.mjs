import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { loadParamSpecs } from '../../deps/effetune/scripts/gen-dsp-params.mjs';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const effetuneRoot = path.join(projectRoot, '../deps/effetune');

const fail = message => {
  throw new Error(message);
};

const cppString = value => JSON.stringify(value)
  .replaceAll('\u2028', '\\u2028')
  .replaceAll('\u2029', '\\u2029');

const parsePluginManifest = () => {
  const manifestPath = path.join(effetuneRoot, 'plugins/plugins.txt');
  const entries = new Map();
  let inPlugins = false;
  for (const originalLine of fs.readFileSync(manifestPath, 'utf8').split(/\r?\n/u)) {
    const line = originalLine.trim();
    if (line === '[plugins]') {
      inPlugins = true;
      continue;
    }
    if (line.startsWith('[')) {
      inPlugins = false;
      continue;
    }
    if (!inPlugins || line.length === 0 || line.startsWith('#')) continue;
    const match = /^([^:]+):\s*([^|]+)\|\s*([^|]+)\|\s*([^|]+)(?:\||$)/u.exec(line);
    if (!match) fail(`cannot parse EffeTune plugin manifest line: ${originalLine}`);
    const entry = {
      path: match[1].trim(),
      displayName: match[2].trim(),
      category: match[3].trim(),
      type: match[4].trim()
    };
    if (entries.has(entry.type)) fail(`duplicate EffeTune plugin type ${entry.type}`);
    entries.set(entry.type, entry);
  }
  return entries;
};

const parseRegistry = () => {
  const registryPath = path.join(effetuneRoot, 'dsp/registry.inc');
  const entries = [];
  const pattern = /^\s*EFFETUNE_PLUGIN\(([^,]+),\s*([^)]+)\)\s*$/gmu;
  const source = fs.readFileSync(registryPath, 'utf8');
  for (const match of source.matchAll(pattern)) {
    entries.push({ type: match[1].trim(), path: match[2].trim() });
  }
  if (entries.length === 0) fail('EffeTune DSP registry is empty');
  return entries;
};

const numberLiteral = value => {
  if (!Number.isFinite(value)) fail(`cannot generate non-finite value ${String(value)}`);
  return Object.is(value, -0) ? '-0.0' : String(value);
};

const identifier = value => value.replaceAll(/[^A-Za-z0-9_]/gu, '_');

const emitElement = (field, index, enumName) => {
  const kind = {
    float: 'ParameterKind::floating',
    int: 'ParameterKind::integer',
    bool: 'ParameterKind::boolean',
    enum: 'ParameterKind::enumeration'
  }[field.kind];
  const defaultValue = field.kind === 'bool'
    ? (field.defaults[index] ? 1 : 0)
    : field.kind === 'enum'
      ? field.values.indexOf(field.defaults[index])
      : field.defaults[index];
  const minimum = field.min ?? 0;
  const maximum = field.max ?? 0;
  const enumValues = enumName ? `std::span<const std::string_view>(${enumName})` : '{}';
  return `  ParameterElement{${cppString(field.keys[index])}, ` +
    `${cppString(field.arrayKey ?? '')}, ${cppString(field.objectArrayKey ?? '')}, ` +
    `${cppString(field.memberKey ?? '')}, ${index}u, ${kind}, ` +
    `${numberLiteral(minimum)}, ${numberLiteral(maximum)}, ${numberLiteral(defaultValue)}, ` +
    `${enumValues}}`;
};

const generateCatalog = () => {
  const manifest = parsePluginManifest();
  const registry = parseRegistry();
  const specs = loadParamSpecs(path.join(effetuneRoot, 'dsp/plugins'));
  const specsByType = new Map(specs.map(spec => [spec.type, spec]));
  const registryTypes = new Set();

  const chunks = [
    '// Generated by tools/generate-dsp-catalog.mjs. Do not edit.',
    '#include "dsp_catalog.h"',
    '',
    '#include <array>',
    '#include <span>',
    '#include <string_view>',
    '',
    'namespace pipetune {',
    ''
  ];
  const definitionNames = [];

  for (const entry of registry) {
    if (registryTypes.has(entry.type)) fail(`duplicate EffeTune DSP registry type ${entry.type}`);
    registryTypes.add(entry.type);
    const plugin = manifest.get(entry.type);
    const spec = specsByType.get(entry.type);
    if (!plugin) fail(`DSP registry type ${entry.type} is absent from plugins/plugins.txt`);
    if (!spec) fail(`DSP registry type ${entry.type} has no params.json`);
    if (plugin.path !== entry.path) {
      fail(`DSP path mismatch for ${entry.type}: ${entry.path} != ${plugin.path}`);
    }

    const base = `k${identifier(entry.type)}`;
    const elements = [];
    let packedIndex = 0;
    for (const field of spec.fields) {
      for (let index = 0; index < field.count; ++index) {
        let enumName = null;
        if (field.kind === 'enum') {
          enumName = `${base}Enum${packedIndex}`;
          chunks.push(
            `static constexpr std::array<std::string_view, ${field.values.length}> ${enumName} = {`,
            `  ${field.values.map(cppString).join(', ')}`,
            '};'
          );
        }
        elements.push(emitElement(field, index, enumName));
        ++packedIndex;
      }
    }
    if (packedIndex !== spec.floatCount) {
      fail(`expanded parameter count mismatch for ${entry.type}`);
    }
    chunks.push(
      `static constexpr std::array<ParameterElement, ${elements.length}> ${base}Elements = {`,
      elements.join(',\n'),
      '};'
    );
    const structured = spec.structured
      ? `StructuredParameter{true, ${cppString(spec.structured.key)}, ` +
        `${cppString(spec.structured.defaultValue)}, ${spec.structured.maxItems}u}`
      : 'StructuredParameter{false, {}, {}, 0u}';
    const definitionName = `${base}Definition`;
    chunks.push(
      `static constexpr DspDefinition ${definitionName} = {`,
      `  ${cppString(plugin.displayName)},`,
      `  ${cppString(entry.type)},`,
      `  0x${spec.hash.toString(16).padStart(8, '0')}u,`,
      `  ${spec.floatCount}u,`,
      `  std::span<const ParameterElement>(${base}Elements),`,
      `  ${structured},`,
      `  ${spec.assets.length > 0 ? 'true' : 'false'}`,
      '};',
      ''
    );
    definitionNames.push(definitionName);
  }

  for (const spec of specs) {
    if (!registryTypes.has(spec.type)) {
      fail(`params.json type ${spec.type} is absent from the native DSP registry`);
    }
  }
  const section = manifest.get('SectionPlugin');
  if (!section || section.displayName !== 'Section') {
    fail('EffeTune Section control metadata is missing or renamed');
  }

  chunks.push(
    `static constexpr std::array<DspDefinition, ${definitionNames.length}> kCatalog = {`,
    `  ${definitionNames.join(',\n  ')}`,
    '};',
    '',
    'std::span<const DspDefinition> generatedDspCatalog() {',
    '  return kCatalog;',
    '}',
    '',
    '} // namespace pipetune'
  );
  return `${chunks.join('\n')}\n`;
};

const main = () => {
  const [outputPath, ...extra] = process.argv.slice(2);
  if (!outputPath || extra.length !== 0) {
    fail('usage: generate-dsp-catalog.mjs OUTPUT_CPP');
  }
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, generateCatalog(), 'utf8');
};

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
